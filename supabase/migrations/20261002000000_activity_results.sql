-- ========================================================
-- Registro de resultados por atividade (evolução do paciente)
-- ========================================================
-- Até aqui o app só guardava quantas vezes a atividade foi aberta e por
-- quanto tempo (usage_events/usage_sessions). Esta tabela guarda o
-- DESEMPENHO: uma linha por item resolvido pelo paciente (no Monte a Frase,
-- uma por frase montada), pra o médico acompanhar a evolução.
--
-- Genérica de propósito (coluna activity): outros exercícios podem gravar
-- aqui depois sem nova tabela.
--
-- Acesso:
--   - só o próprio paciente grava, e só em nome dele (patient_id tem que ser
--     o dele); ninguém altera nem apaga (é um registro);
--   - lê: o próprio paciente, o médico dele e os médicos da mesma empresa
--     (is_doctor_of_patient, igual ao resto do app) e o admin.

create table if not exists public.activity_results (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    patient_id uuid not null references public.patients(id) on delete cascade,
    activity text not null,
    session_id text not null,
    item_text text not null,
    moves integer not null default 0 check (moves >= 0),
    hints integer not null default 0 check (hints >= 0),
    seconds integer not null default 0 check (seconds >= 0)
);

create index if not exists activity_results_user_activity_idx
    on public.activity_results (user_id, activity, created_at);
create index if not exists activity_results_patient_idx
    on public.activity_results (patient_id, created_at);

alter table public.activity_results enable row level security;

drop policy if exists "Paciente grava os próprios resultados" on public.activity_results;
create policy "Paciente grava os próprios resultados" on public.activity_results
    for insert to authenticated
    with check (user_id = auth.uid() and patient_id = public.current_patient_id());

drop policy if exists "Leitura dos próprios resultados" on public.activity_results;
create policy "Leitura dos próprios resultados" on public.activity_results
    for select to authenticated
    using (user_id = auth.uid());

drop policy if exists "Médico lê resultados dos seus pacientes" on public.activity_results;
create policy "Médico lê resultados dos seus pacientes" on public.activity_results
    for select to authenticated
    using (public.is_doctor_of_patient(patient_id));

drop policy if exists "Admin lê todos os resultados" on public.activity_results;
create policy "Admin lê todos os resultados" on public.activity_results
    for select to authenticated
    using (public.is_admin());

grant select, insert on public.activity_results to authenticated;
