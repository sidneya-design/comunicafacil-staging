-- ========================================================
-- Exercício novo: Espelho (banco de frases próprio)
-- ========================================================
-- A pessoa lê a frase, se vê na câmera e grava; o vídeo fica só no
-- navegador (nada de Storage aqui). Esta tabela guarda apenas as frases.
--
-- Mesmo modelo de escopo de audio_clips/exercises:
--   * sem dono (admin): frase global, visível pra todos
--   * doctor_user_id/company_id: banco do terapeuta, compartilhado na empresa
--   * patient_id: frase só daquele paciente
-- Diferente de audio_clips, não há liberação por item: o paciente vê todo o
-- banco do próprio terapeuta/empresa. Se precisar liberar frase a frase,
-- dá pra somar um patient_mirror_flags depois no mesmo padrão.

create table if not exists public.mirror_phrases (
    id bigint generated by default as identity primary key,
    phrase text not null,          -- aceita <strong> pra destacar sílabas
    speak_text text,               -- texto lido pelo TTS (sem marcação); nulo = usa a frase sem tags
    sort_order integer not null default 0,
    visible boolean not null default true,
    doctor_user_id uuid references auth.users(id),
    company_id uuid references public.companies(id),
    patient_id uuid references public.patients(id) on delete restrict,
    created_at timestamptz not null default now()
);
alter table public.mirror_phrases enable row level security;

create or replace function public.can_view_mirror_phrase(
    target_company_id uuid,
    target_patient_id uuid,
    target_doctor_user_id uuid
)
returns boolean language sql stable security definer set search_path = public
as $$
    select
        (target_company_id is null and target_patient_id is null and target_doctor_user_id is null)
        or public.is_admin()
        or (target_patient_id is not null and public.current_patient_id() = target_patient_id)
        or (target_patient_id is not null and public.is_doctor_of_patient(target_patient_id))
        or (target_doctor_user_id is not null and target_doctor_user_id = auth.uid())
        or (target_company_id is not null and target_patient_id is null
            and public.user_company_id() = target_company_id)
        -- paciente vê o banco geral (sem paciente) do próprio terapeuta/empresa
        or (target_patient_id is null and exists (
                select 1 from public.patients p
                where p.user_id = auth.uid()
                  and (p.doctor_user_id = target_doctor_user_id or p.company_id = target_company_id)
            ));
$$;
grant execute on function public.can_view_mirror_phrase(uuid, uuid, uuid) to authenticated, anon;

create policy "Leitura de mirror_phrases" on public.mirror_phrases
    for select using (public.can_view_mirror_phrase(company_id, patient_id, doctor_user_id));

create policy "Escrita de admin e médicos em mirror_phrases do próprio banco" on public.mirror_phrases
    for all to authenticated
    using (public.is_admin() or (doctor_user_id is not null and doctor_user_id = auth.uid()))
    with check (public.is_admin() or (doctor_user_id is not null and doctor_user_id = auth.uid()));

create policy "Escrita de médicos no banco da empresa em mirror_phrases" on public.mirror_phrases
    for all to authenticated
    using (doctor_user_id is not null and patient_id is null and company_id is not null and company_id = public.user_company_id())
    with check (doctor_user_id is not null and patient_id is null and company_id is not null and company_id = public.user_company_id());

create index if not exists mirror_phrases_doctor_idx on public.mirror_phrases (doctor_user_id);
create index if not exists mirror_phrases_company_idx on public.mirror_phrases (company_id);

